import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:dartz/dartz.dart';
import 'package:optialeader/feature/admin/data/repo/announcement_repos/announcement_repo_impl.dart';

/// ====================================================================
/// ✅✅✅ ملف تشغيل الهجرات (يُشتغل مرة واحدة فقط) ✅✅✅
/// ====================================================================
/// 
/// وظيفة الملف ده:
/// 1. يمر على كل الإعلانات القديمة اللي مفيش عندها حقل (match_keys) ويحسبها ويحفظها.
/// 2. يمر على كل المستخدمين اللي مفيش عندهم حقل (match_keys) ويحسبها ويحفظها.
///
/// ⚠️ طريقة التشغيل:
/// مش هتحتاج تشغلها كل مرة المستخدم يفتح الأبلكيشن، 
/// إما تشغلها مرة واحدة في main.dart بعد تشغيل Firebase،
/// أو تعمل زر "تشغيل الهجرات" مخفي في صفحة إعدادات الأدمن.
/// ====================================================================

Future<void> runAnnouncementMigrations() async {
  print('🚀 ====================================');
  print('🚀 بدء تشغيل هجرات نظام الإعلانات...');
  print('🚀 ====================================');

  final repo = AnnouncementRepositoryImpl(FirebaseFirestore.instance);

  // ------------------------------------------------------
  // 1️⃣ هجرة الإعلانات القديمة
  // ------------------------------------------------------
  print('⏳ [1/2] جاري فحص الإعلانات القديمة...');
  final Either<String, int> annResult = await repo.migrateOldAnnouncements();
  
  annResult.fold(
    (error) => print('❌ فشلت هجرة الإعلانات: $error'),
    (count) {
      if (count == 0) {
        print('✅ كل الإعلانات محدثة بالفعل (لا يوجد إعلانات قديمة)');
      } else {
        print('✅ تمت هجرة وإضافة match_keys لـ ($count) إعلان بنجاح');
      }
    },
  );

  // ------------------------------------------------------
  // 2️⃣ هجرة بيانات المستخدمين
  // ------------------------------------------------------
  print('⏳ [2/2] جاري فحص بيانات المستخدمين...');
  final Either<String, int> userResult = await repo.migrateUserMatchKeys();
  
  userResult.fold(
    (error) => print('❌ فشلت هجرة المستخدمين: $error'),
    (count) {
      if (count == 0) {
        print('✅ كل المستخدمين محدثين بالفعل (لا يوجد مستخدمين قدام)');
      } else {
        print('✅ تمت هجرة وإضافة match_keys لـ ($count) مستخدم بنجاح');
      }
    },
  );

  print('🚀 ====================================');
  print('🚀 انتهت عملية الهجرة بنجاح!');
  print('🚀 ====================================');
}